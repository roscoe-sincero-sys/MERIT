-- 5. The audit trigger. Not optional: a DEFAULT fires on INSERT only, so without it every UPDATE
--    would leave modifiedBy / modifiedDateUtc stale and a soft delete would record neither who nor when.
-- -------------------------------------------------------------------------------------------
/***********************************************************************************************************************
ObjectName:   dbo.trg_au_updt_personRelationship
Author:       MERIT build
CreateDate:   2026-10-24
========================================================================================================================
Description:

Owns the modification and soft-delete audit columns on dbo.personRelationship. Recomputes modifiedDateUtc on every update, and stamps
deletedBy / deletedDateUtc when isDeleted transitions 0 -> 1.

========================================================================================================================
Requirements and Key Dependencies:

dbo.personRelationship and its primary key personRelationshipId. SESSION_CONTEXT (N'AppUser'), set read-only by the application on every connection,
names the signed-in user; ORIGINAL_LOGIN () is the fallback for maintenance sessions.

========================================================================================================================
Notes:

personRelationshipId is an application-generated UNIQUEIDENTIFIER, not an IDENTITY, so an UPDATE could change it and the
inserted / deleted join would then pair the wrong rows. The key is therefore immutable: changing it raises 50010.
The 0 -> 1 test on isDeleted is explicit so a later touch of a row deleted months ago does not move the delete
forward in time. An undelete leaves deleted* alone on purpose. TRIGGER_NESTLEVEL guards against RECURSIVE_TRIGGERS.

========================================================================================================================
Example Usage and Performance:

update dbo.personRelationship set <column> = <value> where personRelationshipId = @id;   -- audit columns follow automatically

One extra set-based UPDATE per statement, touching four columns.

========================================================================================================================
Modification History:

Date:		2026-10-24
Author:		MERIT build
Ticket:		T020-T030
Description:	Initial version.

-----------------------------------------------------------------------------------------------------------------------

***********************************************************************************************************************/
CREATE OR ALTER TRIGGER dbo.trg_au_updt_personRelationship
ON dbo.personRelationship
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM inserted) RETURN;

    IF TRIGGER_NESTLEVEL (@@PROCID, 'AFTER', 'DML') > 1 RETURN;

    IF UPDATE (personRelationshipId)
    BEGIN
        ;THROW 50010, N'dbo.personRelationship.personRelationshipId is immutable.', 1;
    END;

    DECLARE @Now   DATETIME2 (3)  = SYSUTCDATETIME (),
            @Actor NVARCHAR (255) = COALESCE (NULLIF (CAST (SESSION_CONTEXT (N'AppUser') AS NVARCHAR (255)), N''), ORIGINAL_LOGIN ());

    UPDATE t
       SET t.modifiedDateUtc = @Now,
           t.modifiedBy      = CASE WHEN UPDATE (modifiedBy)
                                    THEN COALESCE (NULLIF (i.modifiedBy, N''), @Actor)
                                    ELSE @Actor
                               END,
           t.deletedBy       = CASE WHEN d.isDeleted = 0 AND i.isDeleted = 1 THEN @Actor ELSE t.deletedBy      END,
           t.deletedDateUtc  = CASE WHEN d.isDeleted = 0 AND i.isDeleted = 1 THEN @Now   ELSE t.deletedDateUtc END
      FROM dbo.personRelationship AS t
      JOIN inserted AS i ON i.personRelationshipId = t.personRelationshipId
      JOIN deleted  AS d ON d.personRelationshipId = t.personRelationshipId;
END;
GO

