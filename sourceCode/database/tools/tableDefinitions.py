"""
MERIT table definitions. generateTables.py turns each entry into a re-runnable script under
database/scripts/100_tables, built to the ponytail-sql-objects table template: guarded CREATE,
the 7-column audit block, an AFTER UPDATE audit trigger, filtered unique indexes and an
MS_Description on the table and every column.

Naming is camelCase throughout (project decision). Keys are application-generated, time-ordered
UNIQUEIDENTIFIERs (see Merit.Domain.Ids.TimeOrderedId), never NEWSEQUENTIALID.

rls says which row-level security predicate the table gets in 200_security:
    "tenant"  owningTenantId must be in the caller's resolved tenant set (cases, investigations ...)
    "person"  visible through dbo.personAccess or the owning tenant (persons and their child rows)
    "root"    rootTenantId must be the caller's root tenant (locations, organizations, configuration)
    None      no policy: system reference data, or a table reached only through procedures
"""

