"""
Generates the MERIT table scripts from tableDefinitions.py.

    python sourceCode/database/tools/generateTables.py

Writes, under sourceCode/database/scripts/:
    100_tables/<nnn>_<schema>.<table>.sql   one re-runnable script per table (template: table.sql)
    190_foreignKeys/190_foreignKeys.sql     every foreign key, guarded, after all tables exist
    200_security/210_securityPolicy.sql     row-level security policy over the tables that declare rls

Every generated file follows .claude/skills/ponytail-sql-objects/templates/table.sql, with the project's
camelCase naming and the renamed audit block. The generated files are the deliverable and are checked in;
re-run this script after editing the definitions. Once a table is deployed somewhere, add new columns as
new entries -- the script emits a guarded ALTER TABLE ... ADD for every column, so a populated database
converges as well as an empty one. Never remove a column from the definitions to drop it.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tableDefinitions import TABLES  # noqa: E402

ROOT = Path(__file__).resolve().parents[1] / "scripts"
AUTHOR = "MERIT build"
CREATE_DATE = "2026-10-24"

PROLOGUE = """SET XACT_ABORT ON;
-- sqlcmd defaults QUOTED_IDENTIFIER OFF, the setting is baked in at CREATE time, and a session carrying it OFF
-- cannot write to a table with a filtered index (error 1934). Every unique index here is filtered on isDeleted.
SET QUOTED_IDENTIFIER ON;
GO
"""

AUDIT_DESCRIPTIONS = {
    "isDeleted": "Soft-delete flag. 1 = deleted, 0 = active. This database performs no hard deletes; all reads must "
                 "filter isDeleted = 0.",
    "deletedBy": "Login or application user that soft-deleted the row. Stamped by {trg} when isDeleted transitions 0 -> 1. "
                 "Meaningful only when isDeleted = 1.",
    "deletedDateUtc": "UTC timestamp of the soft delete, stamped by {trg} with the same instant as modifiedDateUtc. "
                      "Meaningful only when isDeleted = 1.",
    "createdBy": "Application user (SESSION_CONTEXT AppUser) or login that inserted the row.",
    "createdDateUtc": "UTC timestamp of row insert.",
    "modifiedBy": "Application user or login that last modified the row. Maintained by {trg}; caller-overridable.",
    "modifiedDateUtc": "UTC timestamp of last modification. Recomputed by {trg} on every update; a caller-supplied "
                       "value is overwritten.",
}


def q(text: str) -> str:
    return text.replace("'", "''")


def audit_block(schema: str, table: str) -> str:
    p = f"DF_{schema}_{table}_"
    return f"""        -- Standard audit columns. Soft delete only. Convention: DF_<schema>_<tableName>_<fieldName>.
        isDeleted       BIT             NOT NULL CONSTRAINT {p}isDeleted       DEFAULT (0),
        deletedBy       NVARCHAR (255)  NOT NULL CONSTRAINT {p}deletedBy       DEFAULT (ORIGINAL_LOGIN ()),
        deletedDateUtc  DATETIME2 (3)   NOT NULL CONSTRAINT {p}deletedDateUtc  DEFAULT (SYSUTCDATETIME ()),
        createdBy       NVARCHAR (255)  NOT NULL CONSTRAINT {p}createdBy       DEFAULT (COALESCE (CAST (SESSION_CONTEXT (N'AppUser') AS NVARCHAR (255)), ORIGINAL_LOGIN ())),
        createdDateUtc  DATETIME2 (3)   NOT NULL CONSTRAINT {p}createdDateUtc  DEFAULT (SYSUTCDATETIME ()),
        modifiedBy      NVARCHAR (255)  NOT NULL CONSTRAINT {p}modifiedBy      DEFAULT (COALESCE (CAST (SESSION_CONTEXT (N'AppUser') AS NVARCHAR (255)), ORIGINAL_LOGIN ())),
        modifiedDateUtc DATETIME2 (3)   NOT NULL CONSTRAINT {p}modifiedDateUtc DEFAULT (SYSUTCDATETIME ())"""


def col_def(t: dict, col: dict) -> str:
    schema, table = t["schema"], t["name"]
    parts = [f"{col['name']:<26}", f"{col['type']:<17}", "NULL" if col["null"] else "NOT NULL"]
    if col["default"] is not None:
        parts.append(f"CONSTRAINT DF_{schema}_{table}_{col['name']} DEFAULT ({col['default']})")
    return " ".join(parts)


def pk_col(t: dict) -> str:
    return t["cols"][0]["name"]


def has_root(t: dict) -> bool:
    return any(col["name"] == "rootTenantId" for col in t["cols"])


def table_script(t: dict) -> str:
    schema, table = t["schema"], t["name"]
    full = f"{schema}.{table}"
    pk = pk_col(t)
    trg = f"trg_au_updt_{table}"
    clustered_elsewhere = has_root(t) and table != "tenant"
    out = [PROLOGUE]
    out.append(f"""/*
    {full}
    {t['desc']}

    Generated by sourceCode/database/tools/generateTables.py from tableDefinitions.py; edit the definition and
    re-generate rather than editing this file. Re-runnable: every CREATE is guarded and later columns are added
    additively.
*/

-- -------------------------------------------------------------------------------------------
-- 1. The table. Guarded, so a second run is a no-op.
-- -------------------------------------------------------------------------------------------
IF OBJECT_ID (N'{full}', N'U') IS NULL
BEGIN
    CREATE TABLE {full}
    (""")
    lines = [f"        {col_def(t, col)}," for col in t["cols"]]
    out.append("\n".join(lines))
    out.append("")
    out.append(audit_block(schema, table) + ",")
    out.append("")
    constraints = [f"        CONSTRAINT PK_{schema}_{table} PRIMARY KEY {'NONCLUSTERED' if clustered_elsewhere else 'CLUSTERED'} ({pk})"]
    out.append(",\n".join(constraints))
    out.append("    );\nEND;\nGO\n")

    # 2. additive columns
    out.append("""-- -------------------------------------------------------------------------------------------
-- 2. Additive columns. Each column is also added on its own when missing, so a table deployed by an
--    earlier release converges on the current definition. A no-op on a fresh install.
-- -------------------------------------------------------------------------------------------""")
    for col in t["cols"][1:]:
        if col["type"] == "ROWVERSION" or not col["null"]:
            # NOT NULL columns without a default cannot be added to a populated table; they ship in the CREATE.
            if col["type"] == "ROWVERSION":
                out.append(f"IF COL_LENGTH (N'{full}', N'{col['name']}') IS NULL\n"
                           f"    ALTER TABLE {full} ADD {col['name']} ROWVERSION NOT NULL;")
            elif col["default"] is not None:
                out.append(f"IF COL_LENGTH (N'{full}', N'{col['name']}') IS NULL\n"
                           f"    ALTER TABLE {full} ADD {col_def(t, col)};")
            continue
        out.append(f"IF COL_LENGTH (N'{full}', N'{col['name']}') IS NULL\n    ALTER TABLE {full} ADD {col_def(t, col)};")
    out.append("GO\n")

    # 3. check constraints
    checks = [(f"CK_{schema}_{table}_{col['name']}", col["check"]) for col in t["cols"] if col.get("check")]
    checks += [(f"CK_{schema}_{table}_{name}", expr) for name, expr in t.get("checks", [])]
    if checks:
        out.append("""-- -------------------------------------------------------------------------------------------
-- 3. Check constraints. System-defined values and cross-column rules.
-- -------------------------------------------------------------------------------------------""")
        for name, expr in checks:
            out.append(f"""IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = N'{name}')
BEGIN
    ALTER TABLE {full} ADD CONSTRAINT {name} CHECK ({expr});
END;
GO""")
        out.append("")

    # 4. indexes
    out.append("""-- -------------------------------------------------------------------------------------------
-- 4. Indexes. The clustered index leads with rootTenantId so each state's rows sit together and the
--    row-level security predicate stays cheap. Unique indexes are filtered on isDeleted = 0.
-- -------------------------------------------------------------------------------------------""")
    idx = []
    if clustered_elsewhere:
        cl_cols = t.get("clusterOn") or f"rootTenantId, {pk}"
        cl_name = "IX_{}_{}_{}".format(schema, table, "_".join(c.strip() for c in cl_cols.split(",")))
        idx.append((cl_name, f"CREATE CLUSTERED INDEX {cl_name}\n        ON {full} ({cl_cols});"))
    for ix in t.get("indexes", []):
        if ix.get("unique"):
            flt = "isDeleted = 0" + (f" AND {ix['filter']}" if ix.get("filter") else "")
            idx.append((ix["name"], f"CREATE UNIQUE INDEX {ix['name']}\n        ON {full} ({ix['cols']})\n        WHERE {flt};"))
        else:
            flt = f"\n        WHERE {ix['filter']}" if ix.get("filter") else ""
            idx.append((ix["name"], f"CREATE INDEX {ix['name']}\n        ON {full} ({ix['cols']}){flt};"))
    # An index replaced by another is dropped first, so a database deployed before the change ends up with the same set.
    for name in t.get("dropIndexes", []):
        out.append(f"""IF EXISTS (SELECT 1
             FROM sys.indexes
            WHERE name      = N'{name}'
              AND object_id = OBJECT_ID (N'{full}'))
BEGIN
    DROP INDEX {name} ON {full};
END;
GO""")
    for name, stmt in idx:
        out.append(f"""IF NOT EXISTS (SELECT 1
                 FROM sys.indexes
                WHERE name      = N'{name}'
                  AND object_id = OBJECT_ID (N'{full}'))
BEGIN
    {stmt}
END;
GO""")
    out.append("")

    # 5. trigger
    out.append(f"""-- -------------------------------------------------------------------------------------------
-- 5. The audit trigger. Not optional: a DEFAULT fires on INSERT only, so without it every UPDATE
--    would leave modifiedBy / modifiedDateUtc stale and a soft delete would record neither who nor when.
-- -------------------------------------------------------------------------------------------
/***********************************************************************************************************************
ObjectName:   {schema}.{trg}
Author:       {AUTHOR}
CreateDate:   {CREATE_DATE}
========================================================================================================================
Description:

Owns the modification and soft-delete audit columns on {full}. Recomputes modifiedDateUtc on every update, and stamps
deletedBy / deletedDateUtc when isDeleted transitions 0 -> 1.

========================================================================================================================
Requirements and Key Dependencies:

{full} and its primary key {pk}. SESSION_CONTEXT (N'AppUser'), set read-only by the application on every connection,
names the signed-in user; ORIGINAL_LOGIN () is the fallback for maintenance sessions.

========================================================================================================================
Notes:

{pk} is an application-generated UNIQUEIDENTIFIER, not an IDENTITY, so an UPDATE could change it and the
inserted / deleted join would then pair the wrong rows. The key is therefore immutable: changing it raises 50010.
The 0 -> 1 test on isDeleted is explicit so a later touch of a row deleted months ago does not move the delete
forward in time. An undelete leaves deleted* alone on purpose. TRIGGER_NESTLEVEL guards against RECURSIVE_TRIGGERS.

========================================================================================================================
Example Usage and Performance:

update {full} set <column> = <value> where {pk} = @id;   -- audit columns follow automatically

One extra set-based UPDATE per statement, touching four columns.

========================================================================================================================
Modification History:

Date:		{CREATE_DATE}
Author:		{AUTHOR}
Ticket:		T020-T030
Description:	Initial version.

-----------------------------------------------------------------------------------------------------------------------

***********************************************************************************************************************/
CREATE OR ALTER TRIGGER {schema}.{trg}
ON {full}
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (SELECT 1 FROM inserted) RETURN;

    IF TRIGGER_NESTLEVEL (@@PROCID, 'AFTER', 'DML') > 1 RETURN;

    IF UPDATE ({pk})
    BEGIN
        ;THROW 50010, N'{full}.{pk} is immutable.', 1;
    END;

    DECLARE @Now   DATETIME2 (3)  = SYSUTCDATETIME (),
            @Actor NVARCHAR (255) = COALESCE (NULLIF (CAST (SESSION_CONTEXT (N'AppUser') AS NVARCHAR (255)), N''), ORIGINAL_LOGIN ());

    UPDATE t
       SET t.modifiedDateUtc = @Now,
           t.modifiedBy      = CASE WHEN UPDATE (modifiedBy)
                                    THEN COALESCE (NULLIF (i.modifiedBy, N''), @Actor)
                                    ELSE @Actor
                               END,
           t.deletedBy       = CASE WHEN d.isDeleted = 0 AND i.isDeleted = 1 THEN @Actor ELSE t.deletedBy      END,
           t.deletedDateUtc  = CASE WHEN d.isDeleted = 0 AND i.isDeleted = 1 THEN @Now   ELSE t.deletedDateUtc END
      FROM {full} AS t
      JOIN inserted AS i ON i.{pk} = t.{pk}
      JOIN deleted  AS d ON d.{pk} = t.{pk};
END;
GO
""")

    # 6. descriptions
    out.append("""-- -------------------------------------------------------------------------------------------
-- 6. Extended properties: the table, every column, and the trigger. Through util.uspSetObjectDescription,
--    which adds or updates, so a re-run succeeds and improved wording replaces the old.
-- -------------------------------------------------------------------------------------------""")
    out.append(f"EXEC util.uspSetObjectDescription @SchemaName = N'{schema}', @ObjectType = N'TABLE', "
               f"@ObjectName = N'{table}', @Description = N'{q(t['desc'])}';")
    for col in t["cols"]:
        out.append(f"EXEC util.uspSetObjectDescription @SchemaName = N'{schema}', @ObjectType = N'TABLE', "
                   f"@ObjectName = N'{table}', @ColumnName = N'{col['name']}', @Description = N'{q(col['desc'])}';")
    for name, text in AUDIT_DESCRIPTIONS.items():
        out.append(f"EXEC util.uspSetObjectDescription @SchemaName = N'{schema}', @ObjectType = N'TABLE', "
                   f"@ObjectName = N'{table}', @ColumnName = N'{name}', @Description = N'{q(text.format(trg=trg))}';")
    out.append(f"EXEC util.uspSetObjectDescription @SchemaName = N'{schema}', @ObjectType = N'TRIGGER', "
               f"@ObjectName = N'{trg}', @Description = N'Owns the modification and soft-delete audit columns on "
               f"{full}: recomputes modifiedDateUtc on every update and stamps deletedBy / deletedDateUtc on an "
               f"isDeleted 0 -> 1 transition. Rejects a change to {pk}.';")
    out.append("GO\n")
    out.append("""-- -------------------------------------------------------------------------------------------
-- 7. Permissions. None here, deliberately: application logins hold EXECUTE on procedures only and reach
--    this table through ownership chaining. See scripts/000_infrastructure/005_rolesAndLogins.sql.
-- -------------------------------------------------------------------------------------------
""")
    return "\n".join(out)


def fk_script() -> str:
    out = [PROLOGUE, """/*
    Foreign keys for every MERIT table, created after all tables exist. Generated by tools/generateTables.py.
    No ON DELETE CASCADE anywhere: this database never hard-deletes.
*/
"""]
    for t in TABLES:
        schema, table = t["schema"], t["name"]
        seen: dict[str, int] = {}
        for col, ref, refcol in t.get("fks", []):
            rs, rt = ref.split(".")
            base = f"FK_{schema}_{table}_{rs}_{rt}"
            seen[base] = seen.get(base, 0) + 1
            multi = sum(1 for _, r, _ in t["fks"] if r == ref) > 1
            name = f"{base}_{col}" if multi else base
            out.append(f"""IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'{name}')
BEGIN
    ALTER TABLE {schema}.{table}
        ADD CONSTRAINT {name} FOREIGN KEY ({col}) REFERENCES {ref} ({refcol});
END;
GO""")
    return "\n".join(out) + "\n"


def policy_script() -> str:
    head = PROLOGUE + """/*
    Row-level security policy for MERIT. Generated by tools/generateTables.py from the rls attribute of each table.

    Filter predicates hide rows outside the caller's resolved tenant set; block predicates stop a row being
    inserted or moved into a root or tenant outside it. The predicate functions are in 200_security/200_rlsFunctions.sql
    and fail closed: with no scopeKey in SESSION_CONTEXT a non-owner sees nothing.

    Re-runnable: the policy is created once, empty, and each predicate is added only when it is not already on it.
    Adding a predicate to an existing policy requires the policy OFF while it changes, so the batch turns it off,
    adds what is missing and turns it on again, inside one transaction.
*/

IF NOT EXISTS (SELECT 1 FROM sys.security_policies WHERE name = N'tenantIsolationPolicy'
                                                     AND SCHEMA_NAME (schema_id) = N'auth')
BEGIN
    EXEC (N'CREATE SECURITY POLICY auth.tenantIsolationPolicy WITH (STATE = OFF, SCHEMABINDING = ON);');
END;
GO

"""
    stmts = []
    for t in TABLES:
        kind = t.get("rls")
        if not kind:
            continue
        full = f"{t['schema']}.{t['name']}"
        # Filter predicates decide what a session sees; block predicates decide what it may write there: write or full
        # access to create and change, full access to soft delete (isDeleted going to 1).
        if kind == "tenant":
            filt = "auth.tvfTenantPredicate (rootTenantId, owningTenantId)"
            block = "auth.tvfTenantWritePredicate (rootTenantId, owningTenantId, isDeleted)"
        elif kind == "person":
            filt = f"auth.tvfPersonPredicate (rootTenantId, owningTenantId, {t['personCol']})"
            block = f"auth.tvfPersonWritePredicate (rootTenantId, owningTenantId, {t['personCol']}, isDeleted)"
        else:
            filt = "auth.tvfRootPredicate (rootTenantId)"
            block = "auth.tvfRootWritePredicate (rootTenantId, isDeleted)"
        for ptype, fn, op in (("FILTER", filt, ""), ("BLOCK", block, " AFTER INSERT"), ("BLOCK", block, " AFTER UPDATE")):
            op_code = {"": "NULL", " AFTER INSERT": "N'AFTER INSERT'", " AFTER UPDATE": "N'AFTER UPDATE'"}[op]
            stmts.append(f"""IF NOT EXISTS (SELECT 1
                 FROM sys.security_predicates AS sp
                 JOIN sys.security_policies   AS p ON p.object_id = sp.object_id
                WHERE p.name = N'tenantIsolationPolicy'
                  AND sp.target_object_id = OBJECT_ID (N'{full}')
                  AND sp.predicate_type_desc = N'{ptype}'
                  AND (REPLACE (sp.operation_desc, N'_', N' ') = {op_code} OR ({op_code} IS NULL AND sp.operation_desc IS NULL)))
BEGIN
    SET @Changes = @Changes + 1;
    EXEC (N'ALTER SECURITY POLICY auth.tenantIsolationPolicy ADD {ptype} PREDICATE {fn} ON {full}{op};');
END;""")
    body = "\n".join(stmts)
    return head + f"""BEGIN TRANSACTION;

DECLARE @Changes INT = 0;

ALTER SECURITY POLICY auth.tenantIsolationPolicy WITH (STATE = OFF);

{body}

ALTER SECURITY POLICY auth.tenantIsolationPolicy WITH (STATE = ON);

COMMIT TRANSACTION;

IF @Changes > 0 PRINT CONCAT (N'tenantIsolationPolicy: ', @Changes, N' predicate(s) added.');
GO
"""


def main() -> int:
    tdir = ROOT / "100_tables"
    tdir.mkdir(parents=True, exist_ok=True)
    written = set()
    for i, t in enumerate(TABLES, start=1):
        path = tdir / f"{100 + i:03d}_{t['schema']}.{t['name']}.sql"
        path.write_text(table_script(t), encoding="utf-8")
        written.add(path.name)
    # Remove generated scripts this run did not write (renamed or renumbered tables). Hand-written scripts stay.
    for f in tdir.glob("*.sql"):
        if f.name not in written and "generateTables.py" in f.read_text(encoding="utf-8")[:2000]:
            f.unlink()
    fdir = ROOT / "190_foreignKeys"
    fdir.mkdir(parents=True, exist_ok=True)
    (fdir / "190_foreignKeys.sql").write_text(fk_script(), encoding="utf-8")
    sdir = ROOT / "200_security"
    sdir.mkdir(parents=True, exist_ok=True)
    (sdir / "210_securityPolicy.sql").write_text(policy_script(), encoding="utf-8")
    print(f"Generated {len(TABLES)} table scripts, foreign keys and the security policy under {ROOT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
