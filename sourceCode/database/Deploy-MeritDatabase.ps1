<#
.SYNOPSIS
    Installs or updates the MERIT database and all of its objects. Safe to run any number of times.

.DESCRIPTION
    Creates the database when it does not exist, then runs every script under .\scripts in folder and file
    order with sqlcmd -I -C -b:

        000_infrastructure   schemas, util.uspSetObjectDescription, DDL change logging, execution logging,
                             roles and users, schema permissions
        100_tables           one script per table (generated by tools\generateTables.py)
        190_foreignKeys      foreign keys
        200_security         row-level security predicate functions and policy
        300_functions        helper functions
        400_procedures       stored procedures (CREATE OR ALTER, so changed procedures are updated)
        500_seed             shipped reference data (MERGE / NOT EXISTS, so a re-run changes nothing)
        900_demo             synthetic demo tenant, users and records (only with -IncludeDemoData)

    Every script is re-runnable: tables, columns, constraints and indexes are created only when missing,
    views / procedures / functions / triggers use CREATE OR ALTER, and seed data converges. Nothing is
    dropped or truncated.

.PARAMETER ServerInstance
    SQL Server 2022 (or later) instance, e.g. localhost\PORTAL or a server name.

.PARAMETER DatabaseName
    Database to create or update. Default MERIT.

.PARAMETER SqlCredential
    SQL authentication for the deployment. Omit to use Windows authentication. The deploying principal
    needs CREATE DATABASE (first run) and db_owner; -CreateLogins also needs ALTER ANY LOGIN.

.PARAMETER CreateLogins
    Create the SQL logins the web application and the worker connect with, when missing. Their database
    users are mapped to meritWebRole / meritWorkerRole, which hold EXECUTE on procedures only.

.PARAMETER WebLoginPassword / WorkerLoginPassword
    Passwords for new logins. Required with -CreateLogins when the login does not exist yet.

.PARAMETER PlatformAdminUserName / PlatformAdminPassword
    Creates the very first account, the platform administrator, when no account with that name exists. A platform
    administrator manages accounts, roles and master profiles only and sees no records. The password is hashed here
    (ASP.NET Core Identity V3) and only the hash reaches SQL Server; the account enrolls MFA at first sign-in.

.PARAMETER IncludeDemoData
    Also load the synthetic demo tenant tree, users and records (scripts\900_demo). Never on production.

.EXAMPLE
    .\Deploy-MeritDatabase.ps1 -ServerInstance 'localhost\PORTAL'

.EXAMPLE
    $pw = Read-Host -AsSecureString 'meritWeb password'
    .\Deploy-MeritDatabase.ps1 -ServerInstance 'localhost\PORTAL' -CreateLogins -WebLoginPassword $pw -WorkerLoginPassword $pw -IncludeDemoData
#>
[CmdletBinding()]
param(
    [Parameter()] [string] $ServerInstance = 'localhost\PORTAL',
    [Parameter()] [ValidatePattern('^[A-Za-z][A-Za-z0-9_]{0,63}$')] [string] $DatabaseName = 'MERIT',
    [Parameter()] [System.Management.Automation.PSCredential] $SqlCredential,
    [Parameter()] [switch] $CreateLogins,
    [Parameter()] [ValidatePattern('^[A-Za-z][A-Za-z0-9_]{0,63}$')] [string] $WebLogin = 'meritWeb',
    [Parameter()] [ValidatePattern('^[A-Za-z][A-Za-z0-9_]{0,63}$')] [string] $WorkerLogin = 'meritWorker',
    [Parameter()] [securestring] $WebLoginPassword,
    [Parameter()] [securestring] $WorkerLoginPassword,
    [Parameter()] [switch] $IncludeDemoData,
    [Parameter()] [ValidatePattern('^[A-Za-z0-9._@-]{3,100}$')] [string] $PlatformAdminUserName,
    [Parameter()] [securestring] $PlatformAdminPassword
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$scriptRoot = Join-Path $PSScriptRoot 'scripts'
$started    = Get-Date

function Write-Step([string] $Text) { Write-Host ("[{0:HH:mm:ss}] {1}" -f (Get-Date), $Text) }

function ConvertTo-PlainText([securestring] $Secure) {
    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($Secure)
    try { [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) }
    finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
}

function Get-IdentityV3Hash {
    param([securestring] $Secure, [string] $BlocklistDirectory = (Join-Path $PSScriptRoot '..\security'))
    # ASP.NET Core Identity password hash, format V3: 0x01, PRF (2 = HMAC-SHA512), iteration count, salt length, salt,
    # 32-byte subkey; all integers big-endian. The prefix marks NFC normalization, matching Merit.Web.
    $salt = New-Object byte[] 16
    $platformRng = [Security.Cryptography.RandomNumberGenerator]::Create()
    try { $platformRng.GetBytes($salt) } finally { $platformRng.Dispose() }
    $plain = ConvertTo-PlainText $Secure
    $kdf = $null
    try {
        $plain = $plain.Normalize([Text.NormalizationForm]::FormC)
        $platformCodePoints = 0
        for ($platformIndex = 0; $platformIndex -lt $plain.Length; $platformIndex++) {
            if ([char]::IsHighSurrogate($plain[$platformIndex])) { $platformIndex++ }
            $platformCodePoints++
        }
        if ([string]::IsNullOrWhiteSpace($plain) -or $platformCodePoints -lt 15 -or $platformCodePoints -gt 128) {
            throw 'The platform administrator password must contain 15 to 128 Unicode characters.'
        }
        $platformCandidate = $plain.Trim()
        $platformBlocked = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
        foreach ($platformCorpus in @('common-passwords.txt', 'merit-passwords.txt')) {
            $platformBlocklist = Join-Path $BlocklistDirectory $platformCorpus
            if (-not (Test-Path -LiteralPath $platformBlocklist)) { throw 'Package security/ password blocklists with the database deployment scripts.' }
            foreach ($platformEntry in [IO.File]::ReadAllLines($platformBlocklist, [Text.Encoding]::UTF8)) {
                if (-not [string]::IsNullOrWhiteSpace($platformEntry)) { [void]$platformBlocked.Add($platformEntry.Normalize([Text.NormalizationForm]::FormC).Trim()) }
            }
        }
        if ($platformBlocked.Contains($platformCandidate)) { throw 'Choose a platform administrator password that is not on the common-password blocklist.' }
        $platformSuffixCharacters = '0123456789!@#$%^&*()_+-=[]{};:'',.<>/?\|`~"'
        foreach ($platformContext in @($PlatformAdminUserName, 'MERIT')) {
            if ($platformCandidate.StartsWith($platformContext, [StringComparison]::OrdinalIgnoreCase)) {
                $platformTrivial = $true
                foreach ($platformCharacter in $platformCandidate.Substring($platformContext.Length).ToCharArray()) {
                    if ($platformSuffixCharacters.IndexOf($platformCharacter) -lt 0) { $platformTrivial = $false; break }
                }
                if ($platformTrivial) { throw 'Choose a platform administrator password that is not based on the account or service name.' }
            }
        }
        $kdf = New-Object Security.Cryptography.Rfc2898DeriveBytes($plain, $salt, 220000, [Security.Cryptography.HashAlgorithmName]::SHA512)
        $sub = $kdf.GetBytes(32)
    }
    finally { $plain = $null; if ($null -ne $kdf) { $kdf.Dispose() } }
    $be = { param([int] $v) $b = [BitConverter]::GetBytes($v); [Array]::Reverse($b); , $b }
    $blob = [byte[]](@(1) + (& $be 2) + (& $be 220000) + (& $be 16) + $salt + $sub)
    return 'merit-nfc-v1$' + [Convert]::ToBase64String($blob)
}

# ----------------------------------------------------------------------------------------------- sqlcmd
$sqlcmd = Get-Command sqlcmd -ErrorAction SilentlyContinue
if (-not $sqlcmd) {
    throw 'sqlcmd was not found on PATH. Install the SQL Server command line utilities (ODBC sqlcmd 15+ or go-sqlcmd).'
}

function Get-AuthArgs {
    if ($SqlCredential) {
        # The password goes through SQLCMDPASSWORD rather than -P so it never appears on a command line.
        $env:SQLCMDPASSWORD = $SqlCredential.GetNetworkCredential().Password
        return @('-U', $SqlCredential.UserName)
    }
    return @('-E')
}

function Invoke-Sqlcmd2 {
    param(
        [string] $Database,
        [string] $File,
        [string] $Query,
        [hashtable] $Variables = @{}
    )
    $argList = @('-S', $ServerInstance, '-d', $Database) + (Get-AuthArgs) + @('-I', '-C', '-b', '-W', '-f', '65001')
    foreach ($k in $Variables.Keys) { $argList += @('-v', ("{0}={1}" -f $k, $Variables[$k])) }
    if ($File)  { $argList += @('-i', $File) }
    if ($Query) { $argList += @('-Q', $Query) }
    # Windows PowerShell turns native stderr into error records; with 'Stop' the first PRINT would throw.
    # The exit code, not stderr, decides success.
    $saved = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try { $output = & $sqlcmd.Source @argList 2>&1 | ForEach-Object { "$_" } }
    finally { $ErrorActionPreference = $saved }
    $code = $LASTEXITCODE
    return [pscustomobject]@{ ExitCode = $code; Output = ($output | Out-String) }
}

# ----------------------------------------------------------------------------------------------- server check
Write-Step "Connecting to $ServerInstance"
$probe = Invoke-Sqlcmd2 -Database 'master' -Query "SET NOCOUNT ON; SELECT CAST(SERVERPROPERTY('ProductMajorVersion') AS int);"
if ($probe.ExitCode -ne 0) { throw "Cannot connect to $ServerInstance.`n$($probe.Output)" }
$major = [int](($probe.Output -split "`r?`n" | Where-Object { $_ -match '^\s*\d+\s*$' } | Select-Object -Last 1).Trim())
if ($major -lt 16) { throw "SQL Server 2022 (version 16) or later is required; $ServerInstance reports major version $major." }
Write-Step "SQL Server major version $major"

# ----------------------------------------------------------------------------------------------- database
$createDb = @"
SET NOCOUNT ON;
IF DB_ID (N'$DatabaseName') IS NULL
BEGIN
    CREATE DATABASE [$DatabaseName];
    PRINT 'Created database $DatabaseName.';
END
ELSE PRINT 'Database $DatabaseName exists.';
"@
$r = Invoke-Sqlcmd2 -Database 'master' -Query $createDb
if ($r.ExitCode -ne 0) { throw "Could not create database $DatabaseName.`n$($r.Output)" }
Write-Step $r.Output.Trim()

# Snapshot isolation for readers, so queue and dashboard polling never block writers. Converges.
$rcsi = "IF EXISTS (SELECT 1 FROM sys.databases WHERE name = N'$DatabaseName' AND is_read_committed_snapshot_on = 0) ALTER DATABASE [$DatabaseName] SET READ_COMMITTED_SNAPSHOT ON WITH ROLLBACK IMMEDIATE;"
$r = Invoke-Sqlcmd2 -Database 'master' -Query $rcsi
if ($r.ExitCode -ne 0) { throw "Could not set READ_COMMITTED_SNAPSHOT.`n$($r.Output)" }

# ----------------------------------------------------------------------------------------------- logins
if ($CreateLogins) {
    foreach ($pair in @(@($WebLogin, $WebLoginPassword), @($WorkerLogin, $WorkerLoginPassword))) {
        $name = $pair[0]; $secure = $pair[1]
        $exists = Invoke-Sqlcmd2 -Database 'master' -Query "SET NOCOUNT ON; SELECT CASE WHEN SUSER_ID(N'$name') IS NULL THEN 0 ELSE 1 END;"
        if ($exists.Output -match '(?m)^\s*1\s*$') { Write-Step "Login $name exists."; continue }
        if (-not $secure) { throw "Login $name does not exist; pass -$(if ($name -eq $WebLogin) {'WebLoginPassword'} else {'WorkerLoginPassword'})." }
        $plain = (ConvertTo-PlainText $secure).Replace("'", "''")
        $q = "CREATE LOGIN [$name] WITH PASSWORD = N'$plain', DEFAULT_DATABASE = [$DatabaseName], CHECK_POLICY = ON, CHECK_EXPIRATION = OFF;"
        $r = Invoke-Sqlcmd2 -Database 'master' -Query $q
        $plain = $null
        if ($r.ExitCode -ne 0) { throw "Could not create login $name.`n$($r.Output)" }
        Write-Step "Created login $name."
    }
}

# ----------------------------------------------------------------------------------------------- scripts
$folders = Get-ChildItem -Path $scriptRoot -Directory | Sort-Object Name
if (-not $IncludeDemoData) { $folders = $folders | Where-Object { $_.Name -notlike '9*' } }

$vars = @{ DbName = $DatabaseName; WebLogin = $WebLogin; WorkerLogin = $WorkerLogin }

# The first platform administrator. sqlcmd reads scripting variables from the environment, so the hash is never on a
# command line; 'none' means do not create one.
$env:PlatformAdminUserName = 'none'
$env:PlatformAdminPasswordHash = 'none'
if ($PlatformAdminUserName) {
    if (-not $PlatformAdminPassword) { throw 'Pass -PlatformAdminPassword with -PlatformAdminUserName.' }
    $env:PlatformAdminUserName = $PlatformAdminUserName
    $env:PlatformAdminPasswordHash = Get-IdentityV3Hash $PlatformAdminPassword
}
$count = 0
foreach ($folder in $folders) {
    $files = Get-ChildItem -Path $folder.FullName -Filter '*.sql' -File | Sort-Object Name
    foreach ($file in $files) {
        $rel = $file.FullName.Substring($scriptRoot.Length + 1)
        $t0 = Get-Date
        $r = Invoke-Sqlcmd2 -Database $DatabaseName -File $file.FullName -Variables $vars
        $ms = [int]((Get-Date) - $t0).TotalMilliseconds
        if ($r.ExitCode -ne 0) {
            Write-Host $r.Output -ForegroundColor Red
            throw "Deployment stopped: $rel failed (sqlcmd exit code $($r.ExitCode)). Fix the script and run again; completed scripts are safe to re-run."
        }
        $count++
        $notes = ($r.Output -split "`r?`n" | Where-Object { $_.Trim() -ne '' -and $_ -notmatch '^\(\d+ rows? affected\)$' })
        Write-Step ("OK  {0}  ({1} ms)" -f $rel, $ms)
        if ($VerbosePreference -eq 'Continue') { $notes | ForEach-Object { Write-Verbose "    $_" } }
    }
}

# ----------------------------------------------------------------------------------------------- verify
$verify = @"
SET NOCOUNT ON;
SELECT 'tables',     COUNT(*) FROM sys.tables     WHERE SCHEMA_NAME(schema_id) IN ('dbo','auth','config','logs')
UNION ALL SELECT 'procedures', COUNT(*) FROM sys.procedures WHERE SCHEMA_NAME(schema_id) IN ('dbo','auth','config','logs','util')
UNION ALL SELECT 'policies on', COUNT(*) FROM sys.security_policies WHERE is_enabled = 1;
"@
$r = Invoke-Sqlcmd2 -Database $DatabaseName -Query $verify
Write-Host $r.Output

$elapsed = (Get-Date) - $started
Write-Step ("Deployment of {0} on {1} complete: {2} script(s) in {3:mm\:ss}." -f $DatabaseName, $ServerInstance, $count, $elapsed)
Remove-Item Env:\SQLCMDPASSWORD -ErrorAction SilentlyContinue
Remove-Item Env:\PlatformAdminUserName, Env:\PlatformAdminPasswordHash -ErrorAction SilentlyContinue
